const configuredSpeciesDex = Object.fromEntries(
  ((authoredContent.species ?? []) as SpeciesDefinition[]).map((species) => [species.id, species]),
) as Record<string, SpeciesDefinition>;

const applyConfiguredSpeciesOverrides = (species: Record<string, SpeciesDefinition>) => {
  for (const override of (authoredContent.speciesOverrides ?? []) as Partial<SpeciesDefinition>[]) {
    if (!override.id || !species[override.id]) continue;
    species[override.id] = {
      ...species[override.id],
      ...override,
      battleTrait: override.battleTrait
        ? { ...species[override.id].battleTrait, ...override.battleTrait }
        : species[override.id].battleTrait,
      palette: override.palette ? { ...species[override.id].palette, ...override.palette } : species[override.id].palette,
      statBias: override.statBias ? { ...species[override.id].statBias, ...override.statBias } : species[override.id].statBias,
      learnset: override.learnset ?? species[override.id].learnset,
      formTransitions: override.formTransitions ?? species[override.id].formTransitions,
    };
  }
  return species;
};

export const speciesDex: Record<string, SpeciesDefinition> = applyConfiguredSpeciesOverrides({
  ...builtInSpeciesDex,
  ...configuredSpeciesDex,
});
